/**
 * แตก textarea แบบ "ก | ข | ค" เป็นแถว (บรรทัดละ 1 แถว · ตัดช่องว่างรอบช่อง · ข้ามบรรทัดที่มีช่องไม่ว่างน้อยกว่า $min)
 *
 * @return array[] แต่ละแถวเป็น array ของช่อง
 */
function fenix_home_rows( $text, $min = 1 ) {
	$rows = array();
	foreach ( fenix_lines( $text ) as $line ) {
		$cells = array_map( 'trim', explode( '|', $line ) );
		if ( count( array_filter( $cells, 'strlen' ) ) >= $min ) {
			$rows[] = $cells;
		}
	}
	return $rows;
}

