/**
 * แทนตัวแทน {brand} {broker} {server} ด้วยค่าจริง (ทำก่อน escape)
 */
function fenix_guide_tokens( $text ) {
	$text = (string) $text;
	if ( false === strpos( $text, '{' ) ) {
		return $text;
	}
	$brand = trim( (string) fenix_mod( 'hero_title' ) );
	return strtr(
		$text,
		array(
			'{brand}'  => '' !== $brand ? $brand : 'FALCON PRO EA',
			'{broker}' => (string) fenix_mod( 'broker_name' ),
			'{server}' => (string) fenix_mod( 'broker_server' ),
		)
	);
}

/**
 * คลาสโทนของ section · โหมดเข้มใช้ fenix_section_tone() · โหมดขาว/ดำสลับ ใช้ section-alt แทน
 */
function fenix_guide_band( $key, $alt = false, $light_alt = true ) {
	$tone = fenix_section_tone( $key, $alt );
	if ( '' === $tone && $light_alt && ! fenix_is_dark_mode() ) {
		return ' section-alt';
	}
	return $tone;
}

/**
 * รายการแบบมีเครื่องหมายถูก · บรรทัด "หัวข้อ | รายละเอียด" = หัวข้อตัวหนา
 */
function fenix_guide_marks( $text ) {
	$lines = fenix_lines( fenix_guide_tokens( $text ) );
	if ( empty( $lines ) ) {
		return '';
	}
	$html = '<ul class="gd-marks">';
	foreach ( $lines as $line ) {
		$parts = explode( ' | ', $line, 2 );
		$html .= '<li><span class="gd-mark" aria-hidden="true">' . fenix_icon( 'check', 'icon' ) . '</span><span class="gd-mark-text">';
		if ( 2 === count( $parts ) ) {
			$html .= '<strong>' . fenix_text( trim( $parts[0] ) ) . '</strong> ' . fenix_rich_inline( trim( $parts[1] ) );
		} else {
			$html .= fenix_rich_inline( $line );
		}
		$html .= '</span></li>';
	}
	return $html . '</ul>';
}

/**
 * ลำดับขั้นแบบย่อ (ข้อความคั่นด้วย →) · ลูกศรในวงเล็บไม่ถูกตัด
 */
function fenix_guide_flow( $text ) {
	$blocks = preg_split( '/\n\s*\n/', trim( fenix_guide_tokens( $text ) ), 2 );
	$first  = isset( $blocks[0] ) ? trim( $blocks[0] ) : '';
	$rest   = isset( $blocks[1] ) ? trim( $blocks[1] ) : '';
	$items  = array_values( array_filter( array_map( 'trim', (array) preg_split( '/\s*→\s*(?![^()]*\))/u', $first ) ), 'strlen' ) );
	$html   = '';
	if ( count( $items ) > 1 ) {
		$html .= '<ol class="gd-flow">';
		foreach ( $items as $item ) {
			$html .= '<li>' . fenix_rich_inline( $item ) . '</li>';
		}
		$html .= '</ol>';
	} elseif ( '' !== $first ) {
		$html .= fenix_rich_text( $first );
	}
	if ( '' !== $rest ) {
		$html .= '<div class="gd-flow-note">' . fenix_rich_text( $rest ) . '</div>';
	}
	return $html;
}

