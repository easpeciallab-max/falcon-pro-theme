/**
 * URL เต็มของภาพขั้นตอนที่มากับธีม (assets/img/guides/{file}) · คืน '' เมื่อไม่มีไฟล์นั้นจริง
 * ใช้ URL เต็มเสมอ: ค่าของช่องรูปถูก sanitize ด้วย esc_url_raw ถ้าเก็บเป็น path แบบ "assets/..." จะกลายเป็น http://assets/... เมื่อถูกบันทึก
 * ไฟล์ที่ระบุแต่ไม่มีอยู่ = ช่องรูปว่าง (แอดมินเห็นโน้ต) ไม่ใช่รูปเสีย
 */
function fenix_guide_image_url( $file ) {
	$file = ltrim( str_replace( '\\', '/', trim( (string) $file ) ), '/' );
	if ( '' === $file || false !== strpos( $file, '..' ) ) {
		return '';
	}
	$rel = '/assets/img/guides/' . $file;
	return is_file( get_template_directory() . $rel ) ? get_template_directory_uri() . $rel : '';
}

/**
 * ค่าเริ่มต้นของช่องรูป 1 ช่อง
 * $file = ชื่อไฟล์ใน assets/img/guides/ (ภาพที่มากับธีม) · ไม่ระบุหรือไม่มีไฟล์ = ช่องว่าง แอดมินอัปโหลดเองตาม _img_note
 */
function fenix_guide_media_defaults( $key, $alt, $note, $file = '' ) {
	return array(
		$key . '_img'         => fenix_guide_image_url( $file ),
		$key . '_img_mobile'  => '',
		$key . '_img_alt'     => (string) $alt,
		$key . '_img_caption' => '',
		$key . '_img_note'    => '' !== (string) $note ? 'ภาพที่ต้องใส่: ' . $note : '',
	);
}

/**
 * ชื่อไฟล์ภาพที่ข้อมูลขั้นตอนอ้างถึงแต่ไม่มีใน assets/img/guides/ (ตรวจตอนพัฒนา · dev/preview/stubs-guides.php แจ้งเตือนในพรีวิว)
 *
 * @return string[] เช่น 'gmt5_step1: ชื่อไฟล์.webp'
 */
function fenix_guide_missing_images() {
	$sets         = fenix_guide_data();
	$sets['inst'] = fenix_guide_install_data();
	$missing      = array();
	foreach ( $sets as $p => $data ) {
		$steps = isset( $data['steps'] ) ? (array) $data['steps'] : array();
		foreach ( array_values( $steps ) as $idx => $step ) {
			if ( ! empty( $step[4] ) && '' === fenix_guide_image_url( $step[4] ) ) {
				$missing[] = $p . '_step' . ( $idx + 1 ) . ': ' . $step[4];
			}
		}
	}
	return $missing;
}

