 * รายการคู่มือที่ควรอ่านต่อ: How to Install ก่อน แล้วตามลำดับการใช้งาน · เฉพาะเพจที่เผยแพร่แล้ว
 */
function fenix_guide_related_items( $current = '' ) {
	$pages = function_exists( 'fenix_site_pages' ) ? fenix_site_pages() : array();
	$list  = array( 'how-to-install' => 'install' ) + fenix_guide_map();
	$items = array();
	foreach ( $list as $slug => $p ) {
		if ( $slug === $current ) {
			continue;
		}
		$url = function_exists( 'fenix_published_page_url' ) ? fenix_published_page_url( $slug ) : '';
		if ( '' === $url ) {
			continue;
		}
		$name = '';
		if ( isset( $pages[ $slug ] ) ) {
			$name = ! empty( $pages[ $slug ]['menu'] ) ? $pages[ $slug ]['menu'] : $pages[ $slug ]['title'];
		}
		$sub     = 'install' === $p ? fenix_mod( 'install_sub' ) : fenix_mod( $p . '_sub' );
		$items[] = array(
			'name' => '' !== $name ? $name : $slug,
			'url'  => $url,
			'sub'  => fenix_is_placeholder( $sub ) ? '' : fenix_guide_tokens( $sub ), // ตัวแทนในคำโปรย → ค่าจริง (escape ตอนพิมพ์)
		);
	}
	return $items;
}

