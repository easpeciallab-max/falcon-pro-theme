						<p class="gd-dl-note"><?php echo esc_html( $card['note'] ); ?></p>
					<?php endif; ?>
					<a class="btn btn-fire gd-dl-btn" href="<?php echo esc_url( $card['url'] ); ?>" target="_blank" rel="noopener nofollow" data-dl="<?php echo esc_attr( $card['icon'] ); ?>" aria-label="<?php echo esc_attr( trim( $btn . ' ' . $card['label'] . ( '' !== $newtab ? ' (' . $newtab . ')' : '' ) ) ); ?>">
						<span><?php echo esc_html( $btn ); ?></span><?php echo fenix_icon( 'external', 'icon icon-sm' ); // phpcs:ignore WordPress.Security.EscapeOutput ?>
