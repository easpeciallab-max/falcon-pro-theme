										'label'  => trim( $label . ' ' . sprintf( '%02d', $shown ) ),
										'eager'  => $eager,
										'group'  => 'steps-' . $key_prefix,
									)
								);
								if ( $printed ) {
									$eager = false;
								}
								?>
							</div>
						<?php endif; ?>
						<?php
						if ( 1 === $shown && '' !== $dl_prefix ) {
