function fenix_guide_box( $class, $icon, $title, $lines, $note = '' ) {
	$list = fenix_guide_marks( $lines );
	if ( '' === $list ) {
		return;
	}
	$title = fenix_guide_tokens( $title );
	?>
	<aside class="gd-box <?php echo esc_attr( $class ); ?> reveal">
		<div class="gd-box-head">
			<?php echo fenix_icon_badge( $icon, 'green' ); // phpcs:ignore WordPress.Security.EscapeOutput ?>
			<?php if ( '' !== trim( (string) $title ) ) : ?>
				<h2 class="gd-box-title"><?php echo fenix_text( $title ); // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside ?></h2>
			<?php endif; ?>
		</div>
		<?php echo $list; // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside fenix_guide_marks ?>
		<?php if ( '' !== trim( (string) $note ) ) : ?>
			<div class="gd-box-note"><?php echo fenix_rich_text( fenix_guide_tokens( $note ) ); // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside ?></div>
		<?php endif; ?>
	</aside>
	<?php
}

