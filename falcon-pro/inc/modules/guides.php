/**
 * slug ของเพจ → prefix ของชุดข้อมูลใน Customizer (ลำดับ = ลำดับการใช้งานจริง)
 *
 * @return array<string,string>
 */
function fenix_guide_map() {
	return apply_filters(
		'fenix_guide_map',
		array(
			'open-mt5-account' => 'gacct',
			'deposit'          => 'gdep',
			'mt5-login'        => 'gmt5',
			'vps-windows'      => 'gvpsw',
			'vps-android'      => 'gvpsa',
			'vps-ios'          => 'gvpsi',
		)
	);
}

/**
 * prefix ของหน้าคู่มือที่กำลังแสดง ('' = ไม่ใช่หน้าคู่มือแบบขั้นตอน)
 */
function fenix_guide_prefix( $post_id = 0 ) {
	$post_id = $post_id ? (int) $post_id : (int) get_queried_object_id();
	if ( ! $post_id ) {
		return '';
	}
	$slug = (string) get_post_field( 'post_name', $post_id );
	$map  = fenix_guide_map();
	return isset( $map[ $slug ] ) ? $map[ $slug ] : '';
}

