/**
 * การ์ดดาวน์โหลดแอป (แสดงเฉพาะการ์ดที่มีทั้งชื่อและลิงก์)
 */
function fenix_guide_store_cards( $p ) {
	if ( ! in_array( $p, fenix_guide_dl_prefixes(), true ) ) {
		return;
	}
	$cards = array();
	for ( $i = 1; $i <= fenix_guide_dl_count(); $i++ ) {
		$label = trim( (string) fenix_mod( $p . '_dl' . $i . '_label' ) );
		$url   = trim( (string) fenix_mod( $p . '_dl' . $i . '_url' ) );
		if ( '' === $label || '' === $url || '#' === $url ) {
			continue;
		}
		$icon    = strtolower( trim( (string) fenix_mod( $p . '_dl' . $i . '_icon' ) ) );
		$cards[] = array(
			'label' => $label,
			'sub'   => (string) fenix_mod( $p . '_dl' . $i . '_sub' ),
			'steps' => fenix_lines( fenix_mod( $p . '_dl' . $i . '_steps' ) ),
			'url'   => $url,
			'icon'  => in_array( $icon, array( 'apple', 'android', 'windows' ), true ) ? $icon : 'download',
			'note'  => (string) fenix_mod( $p . '_dl' . $i . '_note' ),
		);
	}
	if ( empty( $cards ) ) {
		return;
	}
	$title  = trim( (string) fenix_mod( $p . '_dl_title' ) );
	$btn    = trim( (string) fenix_mod( 'guides_dl_btn' ) );
	$newtab = trim( (string) fenix_mod( 'guides_newtab' ) );
	?>
	<div class="gd-dl reveal">
		<?php if ( '' !== $title ) : ?>
			<p class="gd-dl-title"><?php echo fenix_icon( 'download', 'icon icon-sm' ); // phpcs:ignore WordPress.Security.EscapeOutput ?><span><?php echo fenix_text( $title ); // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside ?></span></p>
		<?php endif; ?>
		<ul class="gd-dl-cards" data-count="<?php echo esc_attr( (string) count( $cards ) ); ?>">
			<?php foreach ( $cards as $card ) : ?>
				<li class="gd-dl-card">
					<div class="gd-dl-head">
						<?php echo fenix_icon_badge( $card['icon'], 'dark' ); // phpcs:ignore WordPress.Security.EscapeOutput ?>
						<div>
							<h3 class="gd-dl-name"><?php echo fenix_text( $card['label'] ); // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside ?></h3>
							<?php if ( '' !== trim( $card['sub'] ) ) : ?>
								<p class="gd-dl-sub"><?php echo esc_html( $card['sub'] ); ?></p>
							<?php endif; ?>
						</div>
					</div>
					<?php if ( ! empty( $card['steps'] ) ) : ?>
						<ol class="gd-dl-steps">
							<?php foreach ( $card['steps'] as $line ) : ?>
								<li><?php echo esc_html( $line ); ?></li>
							<?php endforeach; ?>
						</ol>
					<?php endif; ?>
					<?php if ( '' !== trim( $card['note'] ) ) : ?>
						<p class="gd-dl-note"><?php echo esc_html( $card['note'] ); ?></p>
					<?php endif; ?>
					<a class="btn btn-fire gd-dl-btn" href="<?php echo esc_url( $card['url'] ); ?>" target="_blank" rel="noopener nofollow" data-dl="<?php echo esc_attr( $card['icon'] ); ?>" aria-label="<?php echo esc_attr( trim( $btn . ' ' . $card['label'] . ( '' !== $newtab ? ' (' . $newtab . ')' : '' ) ) ); ?>">
						<span><?php echo esc_html( $btn ); ?></span><?php echo fenix_icon( 'external', 'icon icon-sm' ); // phpcs:ignore WordPress.Security.EscapeOutput ?>
					</a>
				</li>
			<?php endforeach; ?>
		</ul>
	</div>
	<?php
}

