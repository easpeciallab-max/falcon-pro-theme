/**
 * ขั้นตอนทีละขั้น · ข้อความ | ภาพ สลับซ้ายขวา · ขั้นที่ไม่มีภาพใช้ความกว้างเต็ม
 *
 * @param string $key_prefix เช่น 'gvpsw_step' หรือ 'inst_step' (→ {key_prefix}{N}_title)
 * @param string $dl_prefix  prefix ที่มีการ์ดดาวน์โหลดใต้ขั้นที่ 1 ('' = ไม่มี)
 * @param string $note       ข้อความสั้นใต้รายการขั้นตอน
 */
function fenix_guide_steps( $key_prefix, $dl_prefix = '', $note = '' ) {
	$steps = array();
	$admin = current_user_can( 'edit_theme_options' );
	for ( $i = 1; $i <= fenix_guide_step_count(); $i++ ) {
		$key   = $key_prefix . $i;
		$title = trim( fenix_guide_tokens( fenix_mod( $key . '_title' ) ) ); // {broker} {brand} ในหัวข้อ → ค่าจริง (escape ตอนพิมพ์)
		$desc  = trim( (string) fenix_mod( $key . '_desc' ) );
		if ( '' === $title && '' === $desc ) {
			continue;
		}
		/* ต้องตรงกับเงื่อนไขใน fenix_media_slot(): มีรูป หรือแอดมินที่มีโน้ตรอใส่รูป */
		$has_img   = '' !== trim( (string) fenix_mod( $key . '_img' ) );
		$has_note  = '' !== trim( (string) fenix_mod( $key . '_img_note' ) ) || '' !== trim( (string) fenix_mod( $key . '_img_alt' ) );
		$steps[]   = array(
			'n'     => $i,
			'key'   => $key,
			'title' => $title,
			'desc'  => $desc,
			'media' => $has_img || ( $admin && $has_note ),
		);
	}
	if ( empty( $steps ) ) {
		return;
	}
	$any_media = false;
	foreach ( $steps as $step ) {
		$any_media = $any_media || $step['media'];
	}
	$label = trim( (string) fenix_mod( 'guides_img_label' ) );
	$eager = true;
	$shown = 0;
	$media = 0;
	?>
	<section class="section gd-steps-section<?php echo esc_attr( fenix_guide_band( 'install', false, false ) ); ?>" id="steps">
		<div class="container">
			<ol class="gd-steps<?php echo $any_media ? '' : ' gd-steps--text'; ?>">
				<?php foreach ( $steps as $step ) : ?>
					<?php
					$shown++;
					/* สลับซ้ายขวาเฉพาะขั้นที่มีภาพ (ขั้นข้อความล้วนคั่นกลางไม่ทำให้ภาพอยู่ฝั่งเดิมซ้ำ) */
					$step_class = $step['media'] ? ( 0 === $media++ % 2 ? ' gd-step--media' : ' gd-step--media gd-step--flip' ) : ' gd-step--wide';
					?>
					<li class="gd-step<?php echo esc_attr( $step_class ); ?>" id="<?php echo esc_attr( 'step-' . $step['n'] ); ?>">
						<div class="gd-step-body reveal">
							<span class="gd-step-num" aria-hidden="true"><?php echo esc_html( sprintf( '%02d', $shown ) ); ?></span>
							<div class="gd-step-text">
								<h2><?php echo fenix_text( $step['title'] ); // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside ?></h2>
								<?php if ( '' !== $step['desc'] ) : ?>
									<div class="gd-step-desc"><?php echo fenix_rich_text( fenix_guide_tokens( $step['desc'] ) ); // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside ?></div>
								<?php endif; ?>
							</div>
						</div>
						<?php if ( $step['media'] ) : ?>
							<div class="gd-step-media">
								<?php
								$printed = fenix_media_slot(
									$step['key'],
									array(
										'width'  => 1280,
										'height' => 800,
										'label'  => trim( $label . ' ' . sprintf( '%02d', $shown ) ),
										'eager'  => $eager,
										'group'  => 'steps-' . $key_prefix,
									)
								);
								if ( $printed ) {
									$eager = false;
								}
								?>
							</div>
						<?php endif; ?>
						<?php
						if ( 1 === $shown && '' !== $dl_prefix ) {
							fenix_guide_store_cards( $dl_prefix );
						}
						?>
					</li>
				<?php endforeach; ?>
			</ol>
			<?php if ( '' !== trim( (string) $note ) ) : ?>
				<p class="sec-note gd-steps-note reveal"><?php echo fenix_text( fenix_guide_tokens( $note ) ); // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside ?></p>
			<?php endif; ?>
		</div>
	</section>
	<?php
}

/**
