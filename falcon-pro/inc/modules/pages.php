/**
 * รายการสารบัญของเนื้อหายาว จาก $GLOBALS['fenix_toc'] (เติมโดย fenix_collect_toc ตอน the_content)
 * เก็บเฉพาะระดับที่ต้องการ · ข้ามหัวข้อว่าง · ข้ามหัวของกล่อง .related-links ท้ายหน้า (เป็นรายการลิงก์ ไม่ใช่หัวข้อของเนื้อหา)
 * id ของหัวกล่องนั้นถูกเติมตอนกรองเนื้อหา จึงต้องส่ง $content ที่ผ่าน the_content แล้วเข้ามา
 *
 * @param array  $toc     รายการ { level, text, id }
 * @param string $content HTML ที่ผ่านฟิลเตอร์ the_content แล้ว
 * @param array  $levels  ระดับหัวข้อที่เก็บ
 * @return array
 */
function fenix_pages_toc_items( $toc, $content = '', $levels = array( 2 ) ) {
	$skip = array();
	if ( '' !== (string) $content && preg_match_all( '#<div\b[^>]*\bclass="[^"]*\brelated-links\b[^"]*"[^>]*>\s*<h2\b[^>]*\bid="([^"]+)"#i', (string) $content, $m ) ) {
		$skip = $m[1];
	}
	$out = array();
	foreach ( (array) $toc as $item ) {
		if ( empty( $item['id'] ) || ! isset( $item['text'], $item['level'] ) || '' === trim( (string) $item['text'] ) ) {
			continue;
		}
		if ( ! in_array( (int) $item['level'], $levels, true ) || in_array( $item['id'], $skip, true ) ) {
			continue;
		}
		$out[] = $item;
	}
	return $out;
}

