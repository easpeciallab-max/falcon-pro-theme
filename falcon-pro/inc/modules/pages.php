					<p class="pending-slots-head"><?php echo esc_html( $slots ); ?></p>
				<?php endif; ?>
				<ul class="pending-slots"<?php echo '' !== $slots ? ' aria-label="' . esc_attr( $slots ) . '"' : ''; ?>>
					<?php foreach ( $labels as $fenix_slot ) : ?>
						<li><span class="pending-slot-name"><?php echo esc_html( $fenix_slot ); ?></span><span class="pending-slot-wait"><?php echo esc_html( $wait ); ?></span></li>
