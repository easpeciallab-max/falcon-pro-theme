 * template-pricing.php เพิ่มฟิลเตอร์ fenix_keep_words เฉพาะตอนแสดงหน้านั้น · "|" = รอยต่อที่ห้ามตัดบรรทัด (fenix_keep_words ใส่ word joiner ให้)
 * มีผลกับข้อความที่พิมพ์ผ่าน fenix_text() เท่านั้น
 */
function fenix_pages_keep_words( $words ) {
	return array_merge( (array) $words, array( 'แดช|บอร์ด' ) );
}

/**
 * ราคาพร้อมแสดงหรือยัง: มีตัวเลขจริง หรือเป็นแพ็กเกจฟรี (ฟรี / free / 0 · fenix_is_free_price ใน functions.php)
 * X,XXX / ระบุราคา = ยังไม่ใช่ การ์ดแสดงข้อความสอบถามแทน
 */
function fenix_pages_price_ready( $price ) {
	return fenix_pages_has( $price ) && ( (bool) preg_match( '/\d/', (string) $price ) || fenix_is_free_price( $price ) );
}

/**
 * ช่องของตารางเปรียบเทียบ: แทน {pkg1_price} {pkg2_price} {pkg3_price} ด้วยราคาบนการ์ด (หมวด 10)
 * ตารางจึงตามการ์ดเสมอเมื่อเจ้าของแก้ราคาหรือสลับโหมด · โหมดสอบถามราคา หรือราคายังไม่พร้อม = ทั้งช่องเป็นข้อความสอบถามราคา
 * คืนข้อความล้วน (ยังไม่ escape)
 */
function fenix_pages_compare_cell( $cell ) {
	$cell = (string) $cell;
	if ( false === strpos( $cell, '{pkg' ) ) {
		return $cell;
	}
	$price_mode = 'price' === fenix_mod( 'pricing_mode' );
	$pending    = false;
	$cell       = preg_replace_callback(
		'/\{pkg([1-3])_price\}/',
		function ( $m ) use ( $price_mode, &$pending ) {
			$price = trim( (string) fenix_mod( 'pkg' . $m[1] . '_price' ) );
			if ( ! $price_mode || ! fenix_pages_price_ready( $price ) ) {
				$pending = true;
				return '';
			}
			return $price;
		},
		$cell
	);
	return $pending ? trim( (string) fenix_mod( 'pricing_contact_label' ) ) : trim( (string) $cell );
}

