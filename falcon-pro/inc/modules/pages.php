	$items = array();
	foreach ( fenix_pages_pairs( fenix_mod( 'articles_guides_items' ) ) as $pair ) {
		$slug = sanitize_title( $pair[0] );
		/* เพจที่ถอดออกจากเว็บแล้ว (วิธีติดตั้ง, VPS, Forward Test) ไม่ขึ้นรายการ แม้บรรทัดนั้นยังค้างในค่าที่บันทึกไว้ */
		if ( function_exists( 'fenix_slug_retired' ) && fenix_slug_retired( $slug ) ) {
			continue;
		}
		$url = function_exists( 'fenix_published_page_url' ) ? fenix_published_page_url( $slug ) : '';
		if ( '' === $url ) {
			continue;
		}
		$label = $slug;
