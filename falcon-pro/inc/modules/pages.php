/**
 * แตกบรรทัด "ซ้าย | ขวา" เป็น array( ซ้าย, ขวา )
 */
function fenix_pages_pairs( $text ) {
	$out = array();
	foreach ( fenix_lines( $text ) as $line ) {
		$parts = array_map( 'trim', explode( '|', $line, 2 ) );
		if ( '' === $parts[0] ) {
			continue;
		}
		$out[] = array( $parts[0], isset( $parts[1] ) ? $parts[1] : '' );
	}
	return $out;
}

/**
 * ตัดบรรทัด "ชื่อ | /slug/" ที่ปลายทางเป็นเพจที่ถอดออกจากเว็บแล้ว (วิธีติดตั้ง, VPS, Forward Test)
 * ใช้กับลิงก์ด่วนของหน้า 404 (err404_links): ค่าที่เคยบันทึกไว้ใน Customizer อาจยังมีบรรทัดของเพจกลุ่มนี้
 * ผูกกับฟิลเตอร์ theme_mod_err404_links จึงมีผลกับทุกจุดที่อ่านค่านี้ โดยไม่ต้องแก้เทมเพลต
 */
function fenix_pages_drop_retired_lines( $text ) {
	if ( ! is_string( $text ) || '' === trim( $text ) || ! function_exists( 'fenix_slug_retired' ) ) {
		return $text;
	}
	$keep = array();
	foreach ( (array) preg_split( '/\r\n|\r|\n/', $text ) as $line ) {
		$parts = explode( '|', (string) $line, 2 );
		$dest  = isset( $parts[1] ) ? trim( $parts[1] ) : '';
		if ( '' !== $dest && ! preg_match( '#^(https?:)?//#i', $dest ) && fenix_slug_retired( $dest ) ) {
			continue;
		}
		$keep[] = $line;
	}
	return implode( "\n", $keep );
}
add_filter( 'theme_mod_err404_links', 'fenix_pages_drop_retired_lines' );

/**
 * เก็บผลของฟังก์ชันที่พิมพ์ HTML เป็นสตริง (เช่น ปุ่มติดต่อ เพื่อนำไปวางในแถวปุ่มของหัวเพจ)
