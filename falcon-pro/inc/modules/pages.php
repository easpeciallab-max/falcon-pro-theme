	return array(
		'published'     => $published,
		'published_iso' => $published_iso,
		'modified'      => $modified !== $published ? $modified : '',
		'modified_iso'  => $modified_iso,
		'minutes'       => fenix_pages_reading_minutes( get_the_content() ),
	);
