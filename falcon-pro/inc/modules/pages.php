			$label = ! empty( $pages[ $slug ]['menu'] ) ? $pages[ $slug ]['menu'] : $pages[ $slug ]['title'];
		}
		$items[] = array(
			'label' => $label,
			'url'   => $url,
			'desc'  => $pair[1],
		);
	}
	return $items;
}

